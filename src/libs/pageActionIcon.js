/**
 * 生成地址栏按钮图标 (SVG data URI)。
 * 行为与 TWP 一致：未翻译前为黑白单色，翻译激活后才变为彩色。
 * @param {boolean} isActive 是否处于翻译激活状态
 * @param {boolean} isDark 是否为暗色主题 (prefers-color-scheme)
 * @returns {string} 可直接传给 browser.pageAction.setIcon 的图标地址
 */
export function getPageActionIconPath(isActive = false, isDark = false) {
  const key = isDark ? "dark" : "light";
  const fill = isActive ? ACTIVE_FILLS[key] : IDLE_FILLS[key];
  const fillOpacity = isActive || isDark ? "1" : "0.72";
  const svg = PAGE_ACTION_SVG_XML.replace(/\$\(fill\);/g, fill).replace(
    /\$\(fill-opacity\);/g,
    fillOpacity
  );
  try {
    return "data:image/svg+xml;base64," + btoa(svg);
  } catch (err) {
    // 无 btoa 环境下回退到 manifest 默认图标
    return "images/twp-icon.svg";
  }
}
